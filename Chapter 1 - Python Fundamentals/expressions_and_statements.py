# Expressions and Statements in Python

# An expression evaluates to a value (e.g., 1 + 1, "Roger")
# By themselves in a script, expressions produce no printed output unless printed or assigned:
result = 1 + 1
greeting = "Roger"

# Statements represent an action or command:
name = "Roger"
print("Name:", name)
print("Expression result (1 + 1):", result)