# Indentation in Python

# Indentation is used to define a block of code.

name = "Alok"

if name == "Alok":
    print("Hello, Alok")


# Example with if-else

age = 21

if age >= 18:
    print("You are an adult.")
else:
    print("You are a minor.")


# Example with a loop

for i in range(5):
    print(i)


# Indentation with multiple statements

if age >= 18:
    print("You can vote.")
    print("You are eligible.")