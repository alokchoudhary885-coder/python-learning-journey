# Arithmetic Operators

a = 10
b = 3

print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a % b)
print(a ** b)
print(a // b)


# Comparison Operators

x = 10
y = 5

print(x == y)
print(x > y)
print(x < y)


# Logical Operators

age = 21
has_id = True

print(age >= 18 and has_id)
print(age >= 18 or has_id)
print(not has_id)